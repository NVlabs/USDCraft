import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";

export function cn(...inputs: ClassValue[]): string {
  return twMerge(clsx(inputs));
}

/** Display label of a recorded authoring harness; null when the record carries none. */
export function agentHarnessLabel(harness: "codex" | "provider" | null | undefined): string | null {
  if (harness === "provider") return "Provider";
  if (harness === "codex") return "Codex";
  return null;
}
