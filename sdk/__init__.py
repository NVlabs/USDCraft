def __getattr__(name: str):
    if name in _CADQUERY_EXPORTS:
        from ._extensions import cadquery as _cadquery

        value = getattr(_cadquery, name)
        globals()[name] = value
        return value
    if name in _GEAR_EXPORTS:
        from ._extensions.cadquery import gears as _gears

        value = getattr(_gears, name)
        globals()[name] = value
        return value
    if name == "AssetContext":
        from ._core.assets import AssetContext

        globals()[name] = AssetContext
        return AssetContext
    if name == "save_cadquery_obj":
        from ._extensions.cadquery.cadquery import save_cadquery_obj

        globals()[name] = save_cadquery_obj
        return save_cadquery_obj
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


def __dir__() -> list[str]:
    return sorted(set(globals()) | set(__all__))
